"""Separately labelled corrections of the summaries that fail the evidence audit (no LLM).

The original summaries in ``outputs/<mode>/summaries/summaries.jsonl`` are the evaluated artefacts and are never
changed. This script writes CORRECTED COPIES to ``outputs/<mode>/d3/corrected_summaries/<source>/corrected_summaries.jsonl``:

* each correction is an exact text replacement whose new wording is taken from the product's own aggregate /
  extraction records (the source of every number is stated below);
* every old string must occur exactly once in the original, otherwise nothing is written;
* the corrected copy is re-audited with ``evaluation.d3_audit.audit_summary`` and must pass;
* the copies get a new ``summary_id`` (``<original>-corr1``) and a provenance block, and never enter the summary or
  judgement stores, so the app's evaluated results are unchanged.

Provenance: deterministic correction written by the AI coding assistant (Claude Code) on 2026-11-14 — not generated by
the summariser model, not written or approved by a human.

  python scripts/build_corrected_summaries.py --source dataset__few_shot__qwen2.5-3b__v1
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from config import load_settings  # noqa: E402
from evaluation.d3_audit import audit_summary  # noqa: E402
from pipeline.extraction import ExtractionStore  # noqa: E402
from pipeline.summarization import SummaryStore  # noqa: E402
from schemas.evaluation_schema import ProductSummary  # noqa: E402
from utils.storage import write_json_atomic  # noqa: E402

PROVENANCE = ("deterministic text correction by the AI coding assistant (Claude Code), 2026-11-14, from the product's aggregate "
              "and extraction records; not summariser output; not human-written or human-approved")

# product_id -> list of (old text, new text, source of the new wording)
CORRECTIONS: dict[str, list[tuple[str, str, str]]] = {
    "B001DHKBXU": [
        (f"({n} out of 15 reviews)", f"({n} out of 19 reviews)",
         f"complaint_counts are counted over all total_reviews = 19 (complaint_percentages = count / 19); 15 is reviews_with_complaints")
        for n in ("8", "7", "6", "5", "1")
    ] + [
        ("customer service issues (4 out of 15 reviews), performance issues (4 out of 15 reviews)",
         "customer service issues (4 out of 19 reviews), performance issues (4 out of 19 reviews)",
         "customer_service_issue = 4, performance_issue = 4, total_reviews = 19"),
    ],
    "B0BTY63SFY": [
        ("with positive sentiments from 80% of the reviews.",
         "and 86.7% of the reviews were positive overall.",
         "sentiment_percentages.positive = 86.7 (13 of 15). The original 80% equals the positive share of performance mentions (8 of 10), not of reviews"),
        ("with 67% of negative reviews mentioning these aspects.",
         "with both negative reviews (2 of 2) mentioning these aspects.",
         "negative reviews R80f511ff60c4 (compatibility_fit_issue) and Rd1d0ae81cb05 (performance_issue). The original 67% equals 2 of the 3 reviews with complaints, not of negative reviews"),
    ],
}


def correct(summary: ProductSummary, rules: list[tuple[str, str, str]]) -> tuple[ProductSummary, list[dict]]:
    opinion = summary.content.overall_opinion
    applied = []
    for old, new, source in rules:
        if opinion.count(old) != 1:
            raise ValueError(f"{summary.product_id}: expected exactly one occurrence of {old!r}, found {opinion.count(old)}")
        opinion = opinion.replace(old, new)
        applied.append({"old": old, "new": new, "source": source})
    content = summary.content.model_copy(update={"overall_opinion": opinion})
    return summary.model_copy(update={"summary_id": f"{summary.summary_id}-corr1", "content": content}), applied


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--source", required=True)
    args = p.parse_args()
    s = load_settings()
    mode = s.paths.mode_dir(s.is_mock)
    summaries = {pid: x for (pid, src), x in SummaryStore.for_mode(s, s.is_mock).latest().items() if src == args.source}
    records = ExtractionStore(mode / "extractions" / f"{args.source}.jsonl").records
    out = []
    for pid, rules in CORRECTIONS.items():
        orig = summaries[pid]
        before = audit_summary(orig, records)
        fixed, applied = correct(orig, rules)
        after = audit_summary(fixed, records)
        if not after["ids_and_statistics_verified"]:
            raise SystemExit(f"{pid}: corrected copy still fails the audit: {after['issues']}")
        out.append({"product_id": pid, "original_summary_id": orig.summary_id, "corrected_summary_id": fixed.summary_id,
                    "provenance": PROVENANCE, "replacements": applied,
                    "audit_issues_before": before["issues"], "audit_issues_after": after["issues"],
                    "original_overall_opinion": orig.content.overall_opinion,
                    "corrected_summary": fixed.model_dump(mode="json")})
    d = mode / "d3" / "corrected_summaries" / args.source
    d.mkdir(parents=True, exist_ok=True)
    (d / "corrected_summaries.jsonl").write_text("".join(json.dumps(x, ensure_ascii=False) + "\n" for x in out), encoding="utf-8")
    write_json_atomic(d / "README.json", {"provenance": PROVENANCE, "originals_unchanged": True,
                                          "note": "Corrected copies only; the evaluated originals, their judgements and the negative control use the original summaries.",
                                          "judge_scores": "None. The corrected copies have never been judged. Every stored v1/v2 judgement and negative-control "
                                                          "score refers to the ORIGINAL summary_id and must not be attributed to a corrected copy.",
                                          "products": [x["product_id"] for x in out]})
    for x in out:
        print(f"{x['product_id']}: {len(x['replacements'])} replacement(s); issues before {len(x['audit_issues_before'])}, after {len(x['audit_issues_after'])}")


if __name__ == "__main__":
    main()
