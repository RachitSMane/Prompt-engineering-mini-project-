"""ReviewIQ design tokens: the single source of truth for colours, spacing and type.

Pure Python (no Streamlit import) so the Plotly chart builders can share the palette.
`.streamlit/config.toml` mirrors the colour values for Streamlit's native widgets, and
`ui/styles.css` uses them through the CSS variables generated by `css_variables()`.
"""

from __future__ import annotations

COLORS = {
    "bg": "#0B0F19",
    "sidebar": "#080C14",
    "surface": "#111827",
    "surface_2": "#151E2E",
    "elevated": "#1B2638",
    "text": "#F1F5F9",
    "text_2": "#94A3B8",
    "muted": "#64748B",
    "border": "#263244",
    "border_soft": "#1C2636",
    "accent": "#818CF8",
    "accent_hover": "#6366F1",
}

SENTIMENT = {
    "positive": "#34D399",
    "negative": "#F87171",
    "neutral": "#94A3B8",
    "mixed": "#FBBF24",
}

# Categorical series (prompt strategies, token types). Restrained, distinguishable on dark.
SERIES = ["#818CF8", "#38BDF8", "#E879F9", "#34D399", "#FBBF24"]

SPACING = {"xs": "4px", "sm": "8px", "md": "12px", "lg": "16px", "xl": "24px", "2xl": "32px"}
RADII = {"sm": "4px", "md": "6px", "lg": "8px", "pill": "999px"}
FONT = {
    "family": "Inter, 'Segoe UI', system-ui, -apple-system, sans-serif",
    "mono": "'JetBrains Mono', 'Cascadia Code', Consolas, monospace",
    "xs": "11px",
    "sm": "12px",
    "base": "14px",
    "lg": "16px",
    "kpi": "26px",
}

TONES = {  # badge / callout tones: (foreground, translucent background)
    "accent": (COLORS["accent"], "rgba(129,140,248,0.12)"),
    "positive": (SENTIMENT["positive"], "rgba(52,211,153,0.12)"),
    "negative": (SENTIMENT["negative"], "rgba(248,113,113,0.12)"),
    "neutral": (SENTIMENT["neutral"], "rgba(148,163,184,0.12)"),
    "mixed": (SENTIMENT["mixed"], "rgba(251,191,36,0.12)"),
    "warning": (SENTIMENT["mixed"], "rgba(251,191,36,0.10)"),
}


def css_variables() -> str:
    """`:root` block exposing the tokens to ui/styles.css."""
    lines = [f"--riq-{k.replace('_', '-')}: {v};" for k, v in COLORS.items()]
    lines += [f"--riq-{k}: {v};" for k, v in SENTIMENT.items()]
    lines += [f"--riq-space-{k}: {v};" for k, v in SPACING.items()]
    lines += [f"--riq-radius-{k}: {v};" for k, v in RADII.items()]
    lines += [f"--riq-font: {FONT['family']};", f"--riq-mono: {FONT['mono']};"]
    for name, (fg, bg) in TONES.items():
        lines += [f"--riq-{name}-fg: {fg};", f"--riq-{name}-bg: {bg};"]
    return ":root {" + "".join(lines) + "}"
